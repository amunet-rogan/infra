#!/usr/bin/env bash
# Rebuild amunet/nginx/http.amunet-rogan.conf from all tools/*/*/config.env files.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS_DIR="$REPO_ROOT/amunet/tools"
TEMPLATE="$REPO_ROOT/templates/nginx-location.template"
OUTPUT="$REPO_ROOT/amunet/nginx/http.amunet-rogan.conf"
SERVICES="$REPO_ROOT/site-src/data/services.json"

# Porty sluzeb ze services.json pro sondu /_probe/<port>/ (viz nize).
# "http" = backend na holem http, "https" = vlastni TLS (Portainer).
probe_ports() {  # probe_ports http|https
    python3 - "$SERVICES" "$1" <<'PY'
import json, sys
d = json.load(open(sys.argv[1], encoding="utf-8"))
want = sys.argv[2]
ports = sorted({s["port"] for s in d["services"] if "port" in s and s.get("upstream", "http") == want})
print("|".join(str(p) for p in ports))
PY
}
PROBE_HTTP="$(probe_ports http)"
PROBE_HTTPS="$(probe_ports https)"

mkdir -p "$(dirname "$OUTPUT")"

{
    cat <<'HEADER'
# Auto-generated by amunet-rogan/infra — scripts/regenerate-nginx-conf.sh
# DO NOT EDIT BY HAND. Source of truth: github.com/amunet-rogan/infra

server {
    listen 80;
    listen [::]:80;
    server_name amunet.tail49d1b.ts.net;

    # Web Amunetu — staticke self-contained stranky, zdroj: site-src/ v tomhle repu.
    #   /              rozcestnik
    #   /sluzby/       seznam sluzeb
    #   /pro-martina/  prirucka
    # "^~" prefixy maji prednost pred regexy, takze je catchall nastroju nize
    # nespolkne. absolute_redirect off drzi presmerovani relativni, aby fungovalo
    # pres http i pres https (tailscale serve :443 -> :80).
    root /volume1/docker/amunet-rogan/site;
    absolute_redirect off;

    location = / {
        try_files /index.html =404;
        add_header Cache-Control "no-cache";
    }

    location = /sluzby      { return 301 /sluzby/; }
    location ^~ /sluzby/ {
        try_files $uri $uri/index.html =404;
        add_header Cache-Control "no-cache";
    }

    location = /pro-martina { return 301 /pro-martina/; }
    location ^~ /pro-martina/ {
        try_files $uri $uri/index.html =404;
        add_header Cache-Control "no-cache";
    }

    location = /favicon.ico {
        return 204;
        access_log off;
    }

HEADER

    # Sonda dostupnosti pro /sluzby/. Stejny origin jako stranka, takze funguje
    # i kdyz je stranka otevrena pres HTTPS (prime http:// sondy by prohlizec
    # zablokoval jako mixed content). Jen HEAD, jen porty ze services.json,
    # klient dostane jen status: 502/504 = nebezi, cokoliv jineho = bezi.
    # Hlavicky, podle kterych by prohlizec neco udelal, se nepropousti — odpoved
    # je pod originem stranky: WWW-Authenticate (CouchDB 401) by otevrel prihlasovaci
    # okno, Link (Karakeep) prednacital cizi fonty, HSTS by pripnul jmeno na https,
    # Clear-Site-Data by smazal localStorage.
    probe_block() {  # probe_block <regex of ports> <scheme> [extra directive]
        [[ -n $1 ]] || return 0
        cat <<PROBE
    location ~ ^/_probe/($1)/\$ {
        if (\$request_method != HEAD) { return 405; }
        proxy_pass $2://127.0.0.1:\$1/;${3:-}
        proxy_pass_request_headers off;
        proxy_pass_request_body off;
        proxy_connect_timeout 2s;
        proxy_read_timeout 4s;
        proxy_hide_header Location;
        proxy_hide_header Set-Cookie;
        proxy_hide_header WWW-Authenticate;
        proxy_hide_header Proxy-Authenticate;
        proxy_hide_header Link;
        proxy_hide_header Refresh;
        proxy_hide_header Strict-Transport-Security;
        proxy_hide_header Clear-Site-Data;
        proxy_hide_header Alt-Svc;
        add_header X-Amunet-Probe 1 always;
        add_header Cache-Control "no-store" always;
        access_log off;
    }

PROBE
    }
    probe_block "$PROBE_HTTP" http
    probe_block "$PROBE_HTTPS" https $'\n        proxy_ssl_verify off;'

    if [[ -d "$TOOLS_DIR" ]]; then
        while IFS= read -r config; do
            user_v=$(grep '^USER=' "$config" | cut -d= -f2)
            tool_v=$(grep '^TOOL=' "$config" | cut -d= -f2)
            port_v=$(grep '^INTERNAL_PORT=' "$config" | cut -d= -f2)
            sed \
                -e "s|{USER}|$user_v|g" \
                -e "s|{TOOL}|$tool_v|g" \
                -e "s|{INTERNAL_PORT}|$port_v|g" \
                "$TEMPLATE"
            echo ""
        done < <(find "$TOOLS_DIR" -name 'config.env' 2>/dev/null | sort)
    fi

    cat <<'FOOTER'
    # Catchall for unknown tools — returns 404 instead of falling through to DSM
    location ~ ^/[^/]+/[^/]+/ {
        return 404 "Tool not found. Contact Jenda to onboard.\n";
    }
}
FOOTER
} > "$OUTPUT"

echo "✓ Wrote $OUTPUT"
